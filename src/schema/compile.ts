/**
 * Schema compiler: model definitions → Drizzle table objects for Postgres and SQLite.
 *
 * The Drizzle tables are used for exactly one thing: feeding drizzle-kit's differ (ADR-0004
 * keeps Drizzle behind our own data layer; the repository generates its own SQL). Rules, each
 * proven in spike 01:
 *
 * - Every constraint and index has a **deterministic name** derived from table + column, so two
 *   model versions line up and the differ never sees spurious renames. Names longer than
 *   Postgres' 63-byte limit are shortened deterministically with a hash suffix. The naming
 *   strategy is injectable so the planner can keep the names that exist after a rename.
 * - `enum` is **TEXT + a named CHECK** on both dialects: one portable representation and no
 *   Postgres enum types (whose changes drizzle-kit resolves through interactive prompts).
 * - `decimal` is NUMERIC(p,s) on Postgres and **TEXT** on SQLite: SQLite's NUMERIC affinity
 *   silently converts to floating point and loses precision.
 * - Primary keys are UUIDs generated by the application (UUIDv7), never by the database, so
 *   behaviour is identical on every engine.
 * - Foreign keys are named table constraints (`ON DELETE RESTRICT`), so their names are ours.
 * - With `tenant: true`, unique fields are unique **per tenant**: UNIQUE(tenant_id, col).
 *
 * @module
 */
import { createHash } from 'node:crypto'
import { type SQL, sql } from 'drizzle-orm'
import * as pg from 'drizzle-orm/pg-core'
import * as lite from 'drizzle-orm/sqlite-core'
import { columnName, type ModelDefinition } from '../model/define-model.ts'
import type { FieldDef } from '../model/field.ts'
import { dependencyOrder } from '../model/registry.ts'

/** Kinds of named schema objects. */
export type ConstraintKind = 'unique' | 'index' | 'check' | 'fk' | 'tenantIndex'

/**
 * Naming strategy for constraints and indexes. The default derives names from the current
 * table/column; the migration planner passes a "legacy" strategy after renames.
 */
export type Naming = (kind: ConstraintKind, table: string, column: string) => string

/** Postgres truncates identifiers at 63 bytes; longer names are shortened with a stable hash. */
export function shortenIdentifier(name: string): string {
  if (Buffer.byteLength(name) <= 63) return name
  const hash = createHash('sha256').update(name).digest('hex').slice(0, 8)
  return `${name.slice(0, 54)}_${hash}`
}

const SUFFIX: Readonly<Record<ConstraintKind, string>> = {
  unique: 'unique',
  index: 'idx',
  check: 'check',
  fk: 'fk',
  tenantIndex: 'idx',
}

/** Deterministic default names: `invoices_number_unique`, `invoices_customer_id_fk`, … */
export const defaultNaming: Naming = (kind, table, column) =>
  shortenIdentifier(
    kind === 'tenantIndex' ? `${table}_tenant_id_idx` : `${table}_${column}_${SUFFIX[kind]}`,
  )

/** Options for the compilers. */
export interface CompileOptions {
  /** Constraint/index naming strategy. Defaults to {@link defaultNaming}. */
  readonly naming?: Naming
}

const quoteLiteral = (v: string): string => `'${v.replaceAll("'", "''")}'`

/** CHECK expression restricting an enum column to its allowed values. */
export function enumCheck(column: string, values: readonly string[]): SQL {
  return sql.raw(`"${column}" IN (${values.map(quoteLiteral).join(', ')})`)
}

/** The default as the database should store it (decimals and big integers as strings). */
function storedDefault(def: FieldDef): unknown {
  if (def.default === undefined) return undefined
  if (def.kind === 'decimal' || def.kind === 'bigInteger') return String(def.default)
  return def.default
}

/** Every column the table has, including system columns, in creation order. */
export function tableColumns(model: ModelDefinition): string[] {
  const cols = ['id']
  if (model.options.tenant) cols.push('tenant_id')
  for (const [key, def] of Object.entries(model.fields)) cols.push(columnName(key, def))
  if (model.options.timestamps) cols.push('created_at', 'updated_at')
  if (model.options.softDeletes) cols.push('deleted_at')
  return cols
}

// ───────────────────────────── Postgres ─────────────────────────────

/** A compiled Postgres table. */
export type PgTable = ReturnType<typeof pg.pgTable>
type PgBuilder = pg.PgColumnBuilderBase & { notNull(): PgBuilder; default(v: unknown): PgBuilder }

function pgColumn(def: FieldDef, col: string): PgBuilder {
  const make = (): unknown => {
    switch (def.kind) {
      case 'string':
      case 'email':
        return pg.varchar(col, { length: def.length ?? 255 })
      case 'url':
        return pg.varchar(col, { length: def.length ?? 2048 })
      case 'text':
      case 'enum':
        return pg.text(col)
      case 'uuid':
      case 'belongsTo': // FK added as a named table constraint
        return pg.uuid(col)
      case 'integer':
        return pg.integer(col)
      case 'bigInteger':
        return pg.bigint(col, { mode: 'bigint' })
      case 'decimal':
        return pg.numeric(col, { precision: def.precision ?? 12, scale: def.scale ?? 2 })
      case 'float':
        return pg.doublePrecision(col)
      case 'boolean':
        return pg.boolean(col)
      case 'date':
        return pg.date(col, { mode: 'string' })
      case 'datetime':
        return pg.timestamp(col, { withTimezone: true, mode: 'string' })
      case 'json':
        return pg.jsonb(col)
    }
  }
  let b = make() as PgBuilder
  if (def.required) b = b.notNull()
  const dflt = storedDefault(def)
  if (dflt !== undefined) b = b.default(dflt)
  return b
}

/** Compile models to Postgres tables, keyed by table name. */
export function compilePg(
  models: readonly ModelDefinition[],
  options: CompileOptions = {},
): Record<string, PgTable> {
  const naming = options.naming ?? defaultNaming
  const tables: Record<string, PgTable> = {}
  const byModel = new Map<string, PgTable>()
  const targetId = (target: string): pg.AnyPgColumn => {
    const t = byModel.get(target) as unknown as { id?: pg.AnyPgColumn } | undefined
    if (!t?.id) throw new Error(`Unknown belongsTo target "${target}"`)
    return t.id
  }

  // Targets before dependants, so foreign keys reference already-compiled tables.
  for (const m of dependencyOrder(models)) {
    const cols: Record<string, pg.PgColumnBuilderBase> = { id: pg.uuid('id').primaryKey() }
    if (m.options.tenant) Object.assign(cols, { tenant_id: pg.uuid('tenant_id').notNull() })
    for (const [key, def] of Object.entries(m.fields)) {
      const col = columnName(key, def)
      cols[col] = pgColumn(def, col)
    }
    if (m.options.timestamps) {
      Object.assign(cols, {
        created_at: pg.timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
        updated_at: pg.timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
      })
    }
    if (m.options.softDeletes) {
      Object.assign(cols, { deleted_at: pg.timestamp('deleted_at', { withTimezone: true }) })
    }

    const table = pg.pgTable(m.table, cols, (t) => {
      const c = t as unknown as Record<string, pg.AnyPgColumn>
      const at = (col: string): pg.AnyPgColumn => c[col] as pg.AnyPgColumn
      const extras: (pg.IndexBuilder | pg.CheckBuilder | pg.ForeignKeyBuilder)[] = []
      if (m.options.tenant)
        extras.push(pg.index(naming('tenantIndex', m.table, 'tenant_id')).on(at('tenant_id')))
      if (m.options.softDeletes)
        extras.push(pg.index(naming('index', m.table, 'deleted_at')).on(at('deleted_at')))
      for (const [key, def] of Object.entries(m.fields)) {
        const col = columnName(key, def)
        if (def.unique) {
          const idx = pg.uniqueIndex(naming('unique', m.table, col))
          extras.push(m.options.tenant ? idx.on(at('tenant_id'), at(col)) : idx.on(at(col)))
        }
        if ((def.index || def.kind === 'belongsTo') && !def.unique) {
          extras.push(pg.index(naming('index', m.table, col)).on(at(col)))
        }
        if (def.kind === 'enum')
          extras.push(pg.check(naming('check', m.table, col), enumCheck(col, def.values ?? [])))
        if (def.kind === 'belongsTo') {
          extras.push(
            pg
              .foreignKey({
                name: naming('fk', m.table, col),
                columns: [at(col)],
                foreignColumns: [def.target === m.name ? at('id') : targetId(def.target ?? '')],
              })
              .onDelete('restrict')
              .onUpdate('cascade'),
          )
        }
      }
      return extras
    })
    tables[m.table] = table
    byModel.set(m.name, table)
  }
  return tables
}

// ───────────────────────────── SQLite ─────────────────────────────

/** A compiled SQLite table. */
export type LiteTable = ReturnType<typeof lite.sqliteTable>
type LiteBuilder = lite.SQLiteColumnBuilderBase & {
  notNull(): LiteBuilder
  default(v: unknown): LiteBuilder
}

function liteColumn(def: FieldDef, col: string): LiteBuilder {
  const make = (): unknown => {
    switch (def.kind) {
      case 'integer':
      case 'bigInteger': // SQLite integers are 64-bit; values are returned as strings by the repository
        return lite.integer(col)
      case 'float':
        return lite.real(col)
      case 'boolean':
        return lite.integer(col, { mode: 'boolean' })
      default:
        // string/text/email/url/enum, uuid + belongsTo (canonical lower-case text),
        // decimal (exact text), date ('YYYY-MM-DD'), datetime (canonical UTC ISO-8601), json.
        return lite.text(col)
    }
  }
  let b = make() as LiteBuilder
  if (def.required) b = b.notNull()
  const dflt = storedDefault(def)
  if (dflt !== undefined) b = b.default(def.kind === 'bigInteger' ? Number(dflt) : dflt)
  return b
}

/** Compile models to SQLite tables, keyed by table name. */
export function compileSqlite(
  models: readonly ModelDefinition[],
  options: CompileOptions = {},
): Record<string, LiteTable> {
  const naming = options.naming ?? defaultNaming
  const tables: Record<string, LiteTable> = {}
  const byModel = new Map<string, LiteTable>()
  const targetId = (target: string): lite.AnySQLiteColumn => {
    const t = byModel.get(target) as unknown as { id?: lite.AnySQLiteColumn } | undefined
    if (!t?.id) throw new Error(`Unknown belongsTo target "${target}"`)
    return t.id
  }

  for (const m of dependencyOrder(models)) {
    const cols: Record<string, lite.SQLiteColumnBuilderBase> = { id: lite.text('id').primaryKey() }
    if (m.options.tenant) Object.assign(cols, { tenant_id: lite.text('tenant_id').notNull() })
    for (const [key, def] of Object.entries(m.fields)) {
      const col = columnName(key, def)
      cols[col] = liteColumn(def, col)
    }
    if (m.options.timestamps) {
      // No CURRENT_TIMESTAMP default: SQLite rejects non-constant defaults in ALTER TABLE ADD
      // COLUMN. The repository always sets timestamps.
      Object.assign(cols, {
        created_at: lite.text('created_at').notNull(),
        updated_at: lite.text('updated_at').notNull(),
      })
    }
    if (m.options.softDeletes) Object.assign(cols, { deleted_at: lite.text('deleted_at') })

    const table = lite.sqliteTable(m.table, cols, (t) => {
      const c = t as unknown as Record<string, lite.AnySQLiteColumn>
      const at = (col: string): lite.AnySQLiteColumn => c[col] as lite.AnySQLiteColumn
      const extras: (lite.IndexBuilder | lite.CheckBuilder | lite.ForeignKeyBuilder)[] = []
      if (m.options.tenant)
        extras.push(lite.index(naming('tenantIndex', m.table, 'tenant_id')).on(at('tenant_id')))
      if (m.options.softDeletes)
        extras.push(lite.index(naming('index', m.table, 'deleted_at')).on(at('deleted_at')))
      for (const [key, def] of Object.entries(m.fields)) {
        const col = columnName(key, def)
        if (def.unique) {
          const idx = lite.uniqueIndex(naming('unique', m.table, col))
          extras.push(m.options.tenant ? idx.on(at('tenant_id'), at(col)) : idx.on(at(col)))
        }
        if ((def.index || def.kind === 'belongsTo') && !def.unique) {
          extras.push(lite.index(naming('index', m.table, col)).on(at(col)))
        }
        if (def.kind === 'enum') {
          extras.push(lite.check(naming('check', m.table, col), enumCheck(col, def.values ?? [])))
        }
        if (def.kind === 'belongsTo') {
          extras.push(
            lite
              .foreignKey({
                name: naming('fk', m.table, col),
                columns: [at(col)],
                foreignColumns: [def.target === m.name ? at('id') : targetId(def.target ?? '')],
              })
              .onDelete('restrict')
              .onUpdate('cascade'),
          )
        }
      }
      return extras
    })
    tables[m.table] = table
    byModel.set(m.name, table)
  }
  return tables
}
