/**
 * Generate `.strutvane/types/models.d.ts` from the replayed schema.
 *
 * For each table it writes four shapes, so every layer gets an honest type:
 * - `Post`: a row as the model sees it (`Date` for timestamps, `string` for decimals);
 * - `NewPost`: what creating a post needs (optional where the database or framework fills it);
 * - `PostPatch`: what updating accepts (everything writable, all optional);
 * - `PostJson`: what the API returns (ISO strings for timestamps, secrets removed).
 *
 * It then registers them with `declare module '@strutvane/framework/database'`, which is what makes
 * `class Post extends Model('posts')` fully typed with no import from the app.
 *
 * The output is deterministic: no timestamps, no absolute paths, LF line endings, stable order.
 *
 * @module
 */
import type { ColumnDef, SchemaState, TableState } from '../columns.ts'
import { modelNameForTable } from '../naming.ts'
import { isRequiredOnCreate, isReturnedByApi, isWritable } from './semantics.ts'

/**
 * Options for {@link generateModelTypes}.
 *
 * @example
 * generateModelTypes(state, { modelModule: '@strutvane/framework/database', source: '7 migrations' })
 */
export interface TypeGenerationOptions {
  /** The module whose `TableRegistry` gets augmented. In the product: `@strutvane/framework/model`. */
  readonly modelModule?: string
  /** A short, stable description of where the schema came from, written into the header. */
  readonly source?: string
}

/**
 * Turn the final schema into a `.d.ts` file.
 *
 * @example
 * const dts = generateModelTypes(replay.state, { source: 'database/migrations (7 files)' })
 * writeFileSync('.strutvane/types/models.d.ts', dts)
 */
export function generateModelTypes(
  state: SchemaState,
  options: TypeGenerationOptions = {},
): string {
  const modelModule = options.modelModule ?? '@strutvane/framework/database'
  const lines: string[] = [
    '// Generated by Strutvane from your migrations. Do not edit this file:',
    '// run `node strut migrate` to refresh it.',
    ...(options.source === undefined ? [] : [`// Source: ${options.source}`]),
    '',
    `import type { JsonValue } from ${JSON.stringify(modelModule)}`,
    '',
  ]
  for (const table of state.tables) lines.push(...tableTypes(table), '')
  lines.push('/** Every table, with its four shapes. */', 'export interface Tables {')
  for (const table of state.tables) {
    const model = modelNameForTable(table.name)
    lines.push(
      `  ${table.name}: { row: ${model}; insert: New${model}; update: ${model}Patch; json: ${model}Json }`,
    )
  }
  lines.push('}', '')
  lines.push(
    `declare module ${JSON.stringify(modelModule)} {`,
    '  interface TableRegistry extends Tables {}',
    '}',
    '',
  )
  return lines.join('\n')
}

function tableTypes(table: TableState): string[] {
  const model = modelNameForTable(table.name)
  const writable = table.columns.filter(isWritable)
  return [
    `/** A row of the \`${table.name}\` table. */`,
    `export interface ${model} {`,
    ...table.columns.map((column) => `  ${column.name}: ${rowType(column)}`),
    '}',
    '',
    `/** What creating ${withArticle(humanSingular(model))} needs. Columns the database or framework can fill in are optional. */`,
    `export interface New${model} {`,
    ...writable.map(
      (column) => `  ${column.name}${isRequiredOnCreate(column) ? '' : '?'}: ${inputType(column)}`,
    ),
    '}',
    '',
    `/** What updating ${withArticle(humanSingular(model))} accepts: any writable column. */`,
    `export type ${model}Patch = Partial<New${model}>`,
    '',
    `/** ${capitalize(withArticle(humanSingular(model)))} as the JSON API returns it. */`,
    `export interface ${model}Json {`,
    ...table.columns
      .filter(isReturnedByApi)
      .map((column) => `  ${column.name}: ${jsonType(column)}`),
    '}',
  ]
}

/** The type a model sees once the row is loaded. */
function rowType(column: ColumnDef): string {
  return withNull(column, column.kind === 'timestamp' ? 'Date' : valueType(column))
}

/** What a client may send: decimals as number or string, timestamps as `Date` or ISO string. */
function inputType(column: ColumnDef): string {
  if (column.kind === 'decimal') return withNull(column, 'number | string')
  if (column.kind === 'timestamp') return withNull(column, 'Date | string')
  return withNull(column, valueType(column))
}

/** JSON has no `Date`, so timestamps travel as ISO strings. */
function jsonType(column: ColumnDef): string {
  return withNull(column, column.kind === 'timestamp' ? 'string' : valueType(column))
}

function valueType(column: ColumnDef): string {
  switch (column.kind) {
    case 'id':
    case 'integer':
    case 'bigInteger':
    case 'foreignId':
    case 'double':
      return 'number'
    // Exact decimals can't be JavaScript numbers without losing digits, so they are strings, as in Laravel.
    case 'decimal':
    case 'string':
    case 'text':
    case 'slug':
    case 'uuid':
    // Dates without a time stay 'YYYY-MM-DD' strings: a `Date` would invent a time zone.
    case 'date':
      return 'string'
    case 'boolean':
      return 'boolean'
    case 'enum':
      return (column.values ?? []).map((value) => JSON.stringify(value)).join(' | ')
    case 'timestamp':
      return 'Date'
    case 'json':
      return 'JsonValue'
  }
}

function withNull(column: ColumnDef, type: string): string {
  return column.nullable ? `${type} | null` : type
}

function humanSingular(model: string): string {
  return model.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase()
}

/** "a post", "an author" (by the first letter; good enough for doc comments). */
function withArticle(noun: string): string {
  return `${/^[aeio]/.test(noun) ? 'an' : 'a'} ${noun}`
}

function capitalize(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}
