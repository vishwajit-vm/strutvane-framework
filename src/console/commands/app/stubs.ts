/**
 * The files `make:command`, `make:rule` and `make:observer` write (Laravel's stubs). Every stub
 * compiles under the strictest app tsconfig as generated (a test compiles each one), says
 * `node strut …` in its comments, and only interpolates names that were already validated as
 * identifiers or command names, so nothing typed on the command line can break out of the code.
 *
 * @module
 */
import type { Names } from '../../make/names.ts'

/**
 * A console command: `app/console/commands/<name>.command.ts`.
 *
 * @example
 * commandStub(names('SendReports'), 'app:send-reports')
 */
export function commandStub(n: Names, command: string): string {
  return `import { defineCommand } from '@strutvane/framework/console'

/**
 * \`node strut ${command}\`: describe what it does here.
 *
 * Register it in bootstrap/app.ts: \`.withCommands([${n.camel}Command])\`.
 * Run it with \`node strut ${command}\`; \`node strut help ${command}\` shows its arguments and flags.
 */
export const ${n.camel}Command = defineCommand({
  name: '${command}',
  description: 'Describe what ${command} does',
  args: {
    // recipient: { required: true, description: 'Who gets the report' },
  },
  flags: {
    // preview: { type: 'boolean', description: 'Print instead of sending' },
  },
  examples: ['node strut ${command}'],
  async run({ out }) {
    // ctx.args and ctx.flags are typed from the declarations above.
    out.success('${command} finished.')
    return { data: {} }
  },
})
`
}

/**
 * A validation rule: `app/rules/<name>.rule.ts`, a Zod refinement usable in any form request.
 *
 * @example
 * ruleStub(names('Uppercase'))
 */
export function ruleStub(n: Names): string {
  return `import { z } from 'zod'

/**
 * The ${n.label} rule's check: \`true\` when the value is valid.
 * Generated by \`node strut make:rule ${n.pascal}\`.
 */
export function passes${n.pascal}(value: string): boolean {
  // Replace this with the rule's real check.
  return value.trim() !== ''
}

/**
 * The ${n.label} rule. Use it in a form request's rules():
 *
 * \`\`\`ts
 * rules() {
 *   return z.object({ code: ${n.camel}Rule })
 * }
 * \`\`\`
 */
export const ${n.camel}Rule = z.string().refine(passes${n.pascal}, {
  error: 'The value does not pass the ${n.label.toLowerCase()} rule.',
})
`
}

/** The model events an observer listens to, in the order they are written. */
const OBSERVER_EVENTS: readonly (readonly [method: string, description: string])[] = [
  ['created', 'was created'],
  ['updated', 'was updated'],
  ['deleted', 'was deleted (or soft-deleted)'],
  ['restored', 'was restored from the trash'],
  ['forceDeleted', 'was deleted for good'],
]

/**
 * A model observer: `app/observers/<name>.observer.ts`. `modelImport` is the relative import of
 * the model when its file exists; otherwise the model type is a placeholder to replace.
 *
 * @example
 * observerStub(names('Post'), names('Post'), '../models/post.ts')
 */
export function observerStub(n: Names, model: Names, modelImport: string | undefined): string {
  const type =
    modelImport === undefined
      ? `/** The model this observer watches. Replace with: import type { ${model.pascal} } from '../models/${model.kebab}.ts' */
type ${model.pascal} = object
`
      : `import type { ${model.pascal} } from '${modelImport}'
`
  const methods = OBSERVER_EVENTS.map(
    ([method, description]) => `  /** A ${model.label.toLowerCase()} ${description}. */
  ${method}(${model.camel}: ${model.pascal}): void | Promise<void> {
    void ${model.camel}
  }`,
  ).join('\n\n')
  return `${type}
/**
 * Model events for ${model.pascal}. Generated by \`node strut make:observer ${n.pascal}Observer --model=${model.pascal}\`.
 *
 * Each method runs after its event (inside a transaction: after the commit). Delete the ones you
 * don't need, and attach the observer in a provider's boot().
 */
export class ${n.pascal}Observer {
${methods}
}
`
}
